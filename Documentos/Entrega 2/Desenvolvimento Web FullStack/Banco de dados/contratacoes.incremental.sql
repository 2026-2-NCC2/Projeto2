CREATE TABLE public.contratacoes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proposta_id integer NOT NULL UNIQUE REFERENCES public.propostas(id) ON DELETE RESTRICT,
  cotacao_id integer NOT NULL REFERENCES public.cotacoes(id) ON DELETE RESTRICT,
  evento_id integer NOT NULL REFERENCES public.eventos(id) ON DELETE RESTRICT,
  organizador_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  fornecedor_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  formalizado_por integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  valor_acordado numeric(12,2) NOT NULL CHECK(valor_acordado>=0 AND valor_acordado<10000000000),
  moeda text NOT NULL DEFAULT 'BRL' CHECK(moeda='BRL'),
  servico text NOT NULL,
  condicoes_pagamento text NOT NULL,
  estado text NOT NULL DEFAULT 'ativo' CHECK(estado IN ('ativo','concluido','cancelado')),
  versao integer NOT NULL DEFAULT 1 CHECK(versao>0),
  formalizado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  encerrado_em timestamptz,
  motivo_encerramento text,
  CHECK(formalizado_por=organizador_id AND organizador_id<>fornecedor_id),
  CHECK((estado='ativo' AND encerrado_em IS NULL AND motivo_encerramento IS NULL) OR
    (estado<>'ativo' AND encerrado_em IS NOT NULL AND length(btrim(motivo_encerramento)) BETWEEN 3 AND 1000))
);
CREATE INDEX contratacoes_fornecedor ON public.contratacoes(fornecedor_id,id);
CREATE INDEX contratacoes_evento ON public.contratacoes(evento_id,id);
CREATE INDEX contratacoes_organizador ON public.contratacoes(organizador_id,id);
CREATE TABLE public.contratacoes_auditoria (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contratacao_id integer NOT NULL REFERENCES public.contratacoes(id) ON DELETE RESTRICT,
  autor_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  estado_anterior text,
  estado_novo text NOT NULL CHECK(estado_novo IN ('ativo','concluido','cancelado')),
  motivo text,
  criada_em timestamptz NOT NULL DEFAULT now()
);
