"use strict";
// Somente cluster novo identificado pelo controlador. Sem pools ou .env.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
module.exports=async function({sql,session,pass,folder,manifest,hash,save}) {
  const source=path.resolve(__dirname,'../../Banco de dados/rpc_decidir_solicitacao_acesso.preparacao.sql');
  const rpc=fs.readFileSync(source,'utf8'); manifest.accessSha256=hash(rpc);
  manifest.scenariosSha256=hash(fs.readFileSync(__filename));
  fs.writeFileSync(path.join(folder,'acesso.sql'),rpc); fs.copyFileSync(__filename,path.join(folder,'cenarios-acesso.cjs')); save();
  sql(`BEGIN;
    CREATE TYPE public.usuarios_perfil_enum AS ENUM ('organizador','fornecedor','participante','admin');
    CREATE TYPE public.solicitacoes_acesso_perfil_solicitado_enum AS ENUM ('organizador','fornecedor');
    CREATE TYPE public.solicitacoes_acesso_status_enum AS ENUM ('pendente','aprovado','rejeitado');
    CREATE TABLE public.usuarios(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,perfil public.usuarios_perfil_enum NOT NULL);
    CREATE TABLE public.solicitacoes_acesso(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,usuario_id integer NOT NULL REFERENCES public.usuarios ON DELETE CASCADE,perfil_solicitado public.solicitacoes_acesso_perfil_solicitado_enum NOT NULL,status public.solicitacoes_acesso_status_enum NOT NULL DEFAULT 'pendente');
    CREATE INDEX ON public.solicitacoes_acesso(usuario_id);
    CREATE ROLE service_role NOLOGIN NOSUPERUSER NOBYPASSRLS; CREATE ROLE tt_probe NOLOGIN;
    ${rpc}
    REVOKE ALL ON FUNCTION public.decidir_solicitacao_acesso(bigint,numeric,text) FROM PUBLIC;
    GRANT USAGE ON SCHEMA public TO service_role,tt_probe;
    GRANT SELECT,UPDATE ON public.usuarios,public.solicitacoes_acesso TO service_role;
    GRANT EXECUTE ON FUNCTION public.decidir_solicitacao_acesso(bigint,numeric,text) TO service_role;
    COMMIT;`);
  const user=perfil=>Number(sql(`INSERT INTO public.usuarios(perfil) VALUES ('${perfil}') RETURNING id;`));
  const request=(u,perfil='organizador')=>Number(sql(`INSERT INTO public.solicitacoes_acesso(usuario_id,perfil_solicitado) VALUES (${u},'${perfil}') RETURNING id;`));
  const admin=user('admin'), participant=user('participante');
  const call=(id,status='aprovado',actor=admin)=>`SELECT public.decidir_solicitacao_acesso(${actor},${id},'${status}');`;
  const decide=(id,status='aprovado')=>JSON.parse(sql('SET ROLE service_role; '+call(id,status)));
  const state=()=>JSON.parse(sql(`SELECT jsonb_build_object('usuarios',(SELECT jsonb_agg(to_jsonb(u) ORDER BY id) FROM public.usuarios u),'solicitacoes',(SELECT COALESCE(jsonb_agg(to_jsonb(s) ORDER BY id),'[]') FROM public.solicitacoes_acesso s));`));
  const profile=u=>sql(`SELECT perfil FROM public.usuarios WHERE id=${u};`);
  const status=id=>sql(`SELECT status FROM public.solicitacoes_acesso WHERE id=${id};`);
  function reject(statement,code,role='service_role') {
    const before=state();let error;
    try {sql('\\set VERBOSITY verbose\nSET ROLE '+role+'; '+statement);}catch(e){error=e.message;}
    assert.ok(error?.includes(code),`Expected ${code}: ${error}`); assert.deepEqual(state(),before);
  }
  const pending=request(participant);
  reject(call(pending),'42501','tt_probe');
  sql('GRANT EXECUTE ON FUNCTION public.decidir_solicitacao_acesso(bigint,numeric,text) TO tt_probe;');
  reject(call(pending),'TA403','tt_probe'); reject(call(pending,'aprovado',participant),'TA403');
  pass('EXECUTE separado do guard SQL e perfil admin sintetico');
  reject(call(2147483647),'TA404'); reject(call('1000000000000000000000000000000'),'TA404');
  for(const target of ['organizador','fornecedor']) {
    const u=user('participante'),id=request(u,target);
    assert.deepEqual(decide(id),{mensagem:'Solicitação aprovada com sucesso!'}); assert.equal(profile(u),target);assert.equal(status(id),'aprovado');
    reject(call(id),'TA409'); reject(call(id,'rejeitado'),'TA409');
  }
  pass('compilacao casts entre enums aprovacao e decisoes repetidas');
  const nonParticipant=user('organizador'),notAllowed=request(nonParticipant); reject(call(notAllowed),'TA412');
  // Suppress exactly the conditional UPDATE: PostgreSQL must report zero rows.
  sql(`CREATE SCHEMA tt_harness; CREATE FUNCTION tt_harness.suppress_update() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NULL; END $$; CREATE TRIGGER suppress_update BEFORE UPDATE ON public.usuarios FOR EACH ROW EXECUTE FUNCTION tt_harness.suppress_update();`);
  reject(call(pending),'TA412'); sql('DROP TRIGGER suppress_update ON public.usuarios;');
  pass('aprovacao exige exatamente uma linha atualizada');
  for(const current of ['participante','organizador','fornecedor','admin']) {
    const u=user(current),id=request(u,'fornecedor');
    assert.deepEqual(decide(id,'rejeitado'),{mensagem:'Solicitação rejeitada com sucesso!'});assert.equal(profile(u),current);assert.equal(status(id),'rejeitado');
  }
  pass('rejeicao preserva todos os perfis atuais sem restricao nova');
  const rollbackUser=user('participante'),rollbackId=request(rollbackUser,'fornecedor');
  sql(`CREATE FUNCTION tt_harness.fail_status() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.id=${rollbackId} THEN RAISE EXCEPTION USING ERRCODE='TX004',MESSAGE='failure after profile update'; END IF; RETURN NEW; END $$; CREATE TRIGGER fail_status AFTER UPDATE ON public.solicitacoes_acesso FOR EACH ROW EXECUTE FUNCTION tt_harness.fail_status();`);
  reject(call(rollbackId),'TX004'); assert.equal(profile(rollbackUser),'participante'); assert.equal(status(rollbackId),'pendente');
  sql('DROP TRIGGER fail_status ON public.solicitacoes_acesso;');
  pass('rollback integral perfil e status apos falha de status');
  async function concurrent(same) {
    const u=user('participante'),first=request(u,'organizador'),second=same?first:request(u,'fornecedor');
    const before=state(),x=session('ACCESS_A'),y=session('ACCESS_B');
    await x.wait('PID=');await y.wait('PID=');
    const xp=Number(x.out.match(/PID=(\d+)/)[1]),yp=Number(y.out.match(/PID=(\d+)/)[1]);
    x.send(call(first)+'\n\\echo HELD');await x.wait('HELD');
    y.send('\\set VERBOSITY verbose\n'+call(second,same?'rejeitado':'aprovado')+'\nCOMMIT;\n\\echo UNEXPECTED_SUCCESS\n\\q');
    const until=Date.now()+3500;let blocked=false;
    while(Date.now()<until){if(sql(`SELECT ${xp}=ANY(pg_blocking_pids(${yp}));`)==='t'){blocked=true;break;}await new Promise(r=>setTimeout(r,40));}
    assert.ok(blocked,'Expected actual lock wait');assert.deepEqual(state(),before);
    x.send('COMMIT;\n\\q');
    const end=Date.now()+8000;while(!x.closed||!y.closed){assert.ok(Date.now()<end,'Session exit timeout');await new Promise(r=>setTimeout(r,30));}
    assert.equal(x.code,0,x.err);assert.equal(y.code,3,y.err);assert.ok(y.err.includes(same?'TA409':'TA412'));assert.ok(!y.out.includes('UNEXPECTED_SUCCESS'));
    assert.equal(profile(u),'organizador');assert.equal(status(first),'aprovado');if(!same)assert.equal(status(second),'pendente');
    pass(same?'concorrencia mesma solicitacao':'concorrencia solicitacoes distintas mesmo usuario',{blocker:xp,waiter:yp,observedBlocking:true,isolation:'read committed',expectedSQLState:same?'TA409':'TA412'});
  }
  await concurrent(true);await concurrent(false);
  assert.equal(hash(fs.readFileSync(source,'utf8')),manifest.accessSha256);
  pass('RPC original preservada');
};
