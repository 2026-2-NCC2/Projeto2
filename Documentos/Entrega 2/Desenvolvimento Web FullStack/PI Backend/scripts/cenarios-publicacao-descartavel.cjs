"use strict";
// Somente invocado pelo controlador com cluster novo ja identificado.
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
module.exports=async function(ctx) {
  const {sql,session,pass,item,call,put,rows,literal,a,c,event,empty,foreign,folder,manifest,hash,save}=ctx;
  const source=path.resolve(__dirname,'../../Banco de dados/rpc_publicar_cotacao.preparacao.sql');
  const rpc=fs.readFileSync(source,'utf8');
  manifest.publicationSha256=hash(rpc); manifest.scenariosSha256=hash(fs.readFileSync(__filename));
  fs.writeFileSync(path.join(folder,'publicacao.sql'),rpc); fs.copyFileSync(__filename,path.join(folder,'cenarios-publicacao.cjs')); save();
  sql(`BEGIN;
    CREATE TABLE public.cotacoes(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,evento_id integer NOT NULL REFERENCES public.eventos ON DELETE CASCADE,prazo date NOT NULL,modalidade varchar(50) NOT NULL DEFAULT 'Fechada',observacoes text,status varchar(30) NOT NULL DEFAULT 'Aberta',criada_em timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP);
    CREATE TABLE public.itens_cotacao(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,cotacao_id integer NOT NULL REFERENCES public.cotacoes ON DELETE CASCADE,categoria varchar(100) NOT NULL,descricao varchar(255) NOT NULL,valor_estimado numeric(12,2) NOT NULL);
    CREATE INDEX ON public.cotacoes(evento_id); CREATE INDEX ON public.itens_cotacao(cotacao_id);
    ${rpc}
    REVOKE ALL ON FUNCTION public.publicar_cotacao(bigint,bigint,text,text,text,jsonb) FROM PUBLIC;
    GRANT EXECUTE ON FUNCTION public.publicar_cotacao(bigint,bigint,text,text,text,jsonb) TO service_role;
    GRANT UPDATE ON public.custos_evento TO service_role;
    GRANT SELECT,INSERT ON public.cotacoes,public.itens_cotacao TO service_role;
    GRANT USAGE ON SEQUENCE public.cotacoes_id_seq,public.itens_cotacao_id_seq TO service_role;
    COMMIT;`);
  const publish=(items,ev=event,actor=a,prazo='2026-11-30')=>`SELECT public.publicar_cotacao(${ev},${actor},'${prazo}','2026-10-30','TESTE sintetico',${literal(items)});`;
  const state=()=>JSON.parse(sql(`SELECT jsonb_build_object('cotacoes',(SELECT COALESCE(jsonb_agg(to_jsonb(c) ORDER BY id),'[]') FROM public.cotacoes c),'itens',(SELECT COALESCE(jsonb_agg(to_jsonb(i) ORDER BY id),'[]') FROM public.itens_cotacao i),'custos',(SELECT COALESCE(jsonb_agg(to_jsonb(k) ORDER BY id),'[]') FROM public.custos_evento k));`));
  const snapshot=id=>JSON.parse(sql(`SELECT COALESCE(jsonb_agg(jsonb_build_object('categoria',categoria,'descricao',descricao,'valor_estimado',valor_estimado::text) ORDER BY id),'[]') FROM public.itens_cotacao WHERE cotacao_id=${id};`));
  function reject(statement,code) {
    const before=state(); let failure;
    try {sql('\\set VERBOSITY verbose\nSET ROLE service_role; '+statement);}catch(e){failure=e.message;}
    assert.ok(failure?.includes(code),`Expected ${code}, got ${failure}`); assert.deepEqual(state(),before);
  }
  reject(publish([],foreign),'TP404'); reject(publish([],2147483647),'TP404'); reject(publish([],event,c),'TP403'); reject(publish([],empty),'TP402');
  pass('publicacao propriedade perfil ausente e vazio');
  const reviewed=['0.00','0.10','0.20','9999999999.99'].map((v,i)=>item(v,'TESTE-'+i)); put(reviewed);
  for(const changed of [reviewed.slice(1),[...reviewed].reverse(),reviewed.map((x,i)=>i?x:{...x,valor_estimado:'0.01'}),reviewed.map((x,i)=>i?x:{...x,categoria:'teste-0'})]) reject(publish(changed),'TP409');
  pass('revisao divergente TP409 sem escritas');
  for(const prazo of ['2026-02-30','2026-10-29']) reject(publish(reviewed,event,a,prazo),'TP401');
  const response=JSON.parse(sql('SET ROLE service_role; '+publish(reviewed)));
  assert.deepEqual(response,{id:response.id,evento_id:event,prazo:'2026-11-30',modalidade:'Fechada',observacoes:'TESTE sintetico',status:'Aberta',itens:reviewed});
  assert.ok(Number.isSafeInteger(response.id)&&response.id>0); assert.deepEqual(snapshot(response.id),reviewed);
  // Inspect fields from a separate committed session, never construct persistence from response.
  const saved=state(); assert.equal(saved.cotacoes.length,1); assert.equal(saved.itens.length,4); assert.equal(saved.cotacoes[0].prazo,response.prazo);
  pass('compilacao resposta snapshot ordem e precisao decimal');
  put([item('2.00','NOVO')]); assert.deepEqual(snapshot(response.id),reviewed);
  pass('snapshot permanece apos substituicao de custos');
  const failing=[item('1.00','PRIMEIRO'),item('2.00','FAIL')]; put(failing);
  sql(`CREATE SCHEMA tt_harness; CREATE FUNCTION tt_harness.fail_item() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.categoria='FAIL' THEN RAISE EXCEPTION USING ERRCODE='TX003',MESSAGE='failure after quotation and first item'; END IF; RETURN NEW; END $$; CREATE TRIGGER fail_item AFTER INSERT ON public.itens_cotacao FOR EACH ROW EXECUTE FUNCTION tt_harness.fail_item();`);
  reject(publish(failing),'TX003'); sql('DROP TRIGGER fail_item ON public.itens_cotacao;');
  pass('rollback cotacao e itens apos falha parcial');
  // Calls are real RPC SQL bodies in both sessions. No manual publication-lock probes.
  async function concurrent(mode) {
    const old=[item('3.33','ANTIGO')], next=[item('4.44','NOVO')]; put(old);
    const prior=state(); const x=session('PUB_A'),y=session('PUB_B');
    await x.wait('PID='); await y.wait('PID=');
    const xp=Number(x.out.match(/PID=(\d+)/)[1]),yp=Number(y.out.match(/PID=(\d+)/)[1]);
    const first=mode==='publication-first'?publish(old):call(next);
    const second=mode==='publication-first'?call(next):publish(mode==='put-first-stale'?old:next);
    x.send(first+'\n\\echo HELD'); await x.wait('HELD');
    y.send('\\set VERBOSITY verbose\n'+second+'\nCOMMIT;\n\\echo DONE\n\\q');
    const until=Date.now()+3500; let blocked=false;
    while(Date.now()<until){if(sql(`SELECT ${xp}=ANY(pg_blocking_pids(${yp}));`)==='t'){blocked=true;break;} await new Promise(r=>setTimeout(r,40));}
    assert.ok(blocked,'No actual RPC lock wait'); assert.deepEqual(state(),prior);
    x.send('COMMIT;\n\\q');
    if(mode!=='put-first-stale') await y.wait('DONE');
    const end=Date.now()+8000; while(!x.closed||!y.closed){assert.ok(Date.now()<end,'Session exit timeout');await new Promise(r=>setTimeout(r,30));}
    assert.equal(x.code,0,x.err);
    if(mode==='put-first-stale'){assert.equal(y.code,3);assert.ok(y.err.includes('TP409'));assert.deepEqual(state().cotacoes,prior.cotacoes);assert.deepEqual(state().itens,prior.itens);}
    else {assert.equal(y.code,0,y.err);const current=state();assert.equal(current.cotacoes.length,prior.cotacoes.length+1);const id=current.cotacoes.at(-1).id;assert.deepEqual(snapshot(id),mode==='publication-first'?old:next);}
    assert.deepEqual(rows().map(({categoria,descricao,valor_estimado})=>({categoria,descricao,valor_estimado})),next);
    pass('RPCs reais concorrentes '+mode,{blocker:xp,waiter:yp,observedBlocking:true,isolation:'read committed',publicationExecuted:true,expectedSQLState:mode==='put-first-stale'?'TP409':null});
  }
  await concurrent('put-first'); await concurrent('publication-first'); await concurrent('put-first-stale');
  assert.deepEqual(snapshot(response.id),reviewed);
  assert.equal(hash(fs.readFileSync(source,'utf8')),manifest.publicationSha256);
  pass('cotacao anterior preservada e RPC original intacta');
};
