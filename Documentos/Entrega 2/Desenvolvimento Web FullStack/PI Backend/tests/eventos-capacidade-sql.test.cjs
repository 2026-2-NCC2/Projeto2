'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const dados=()=>({nome:'Sintético',data:'2030-12-10',horario:'10:00',local:'Local',categoria:'Social',publico:900,descricao:''});
test('Etapa 3: integridade e concorrência PostgreSQL descartável',
 {skip:process.env.TROCATICKET_CAPACIDADE_SQL_LOCAL!=='1',timeout:120000},async t=>{
  const {execFileSync}=require('node:child_process'),{Pool}=require('pg'),{randomUUID}=require('node:crypto'),fs=require('node:fs'),path=require('node:path');
  const nome='trocaticket-gestao-'+randomUUID(),senha=randomUUID();let pool;
  execFileSync('docker',['run','--detach','--rm','--pull=never','--name',nome,'-p','127.0.0.1::5432','-e','POSTGRES_PASSWORD='+senha,'postgres:17'],{stdio:'pipe'});
  t.after(async()=>{try{await pool?.end()}finally{execFileSync('docker',['stop','--time','1',nome],{stdio:'pipe'})}});
  for(let i=0;;i++){try{execFileSync('docker',['exec',nome,'pg_isready','-h','127.0.0.1','-U','postgres'],{stdio:'pipe'});break}catch(e){if(i>60)throw e;await new Promise(r=>setTimeout(r,200))}}
  const porta=Number(execFileSync('docker',['port',nome,'5432/tcp'],{encoding:'utf8'}).trim().split(':').at(-1));
  pool=new Pool({host:'127.0.0.1',port:porta,user:'postgres',password:senha,database:'postgres',max:12,query_timeout:10000});
  await pool.query(`CREATE ROLE service_role BYPASSRLS;CREATE ROLE anon;CREATE ROLE authenticated;
    CREATE COLLATION public.trocaticket_general_ci(provider=icu,locale='und-u-ks-level1',deterministic=false);
    CREATE FUNCTION public.btrim(character varying) RETURNS text LANGUAGE sql IMMUTABLE AS $$ SELECT 'ADULTERADO'::text $$;
    CREATE TABLE usuarios(id integer PRIMARY KEY,perfil text NOT NULL);INSERT INTO usuarios VALUES(7,'organizador'),(8,'organizador'),(9,'participante');
    CREATE TABLE contas_teste_imagens(usuario_id integer,estado text);
    CREATE TABLE eventos(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nome varchar(100) COLLATE public.trocaticket_general_ci NOT NULL,data date NOT NULL,horario time NOT NULL,
      local varchar(200) COLLATE public.trocaticket_general_ci NOT NULL,categoria varchar(100) COLLATE public.trocaticket_general_ci,publico integer NOT NULL,descricao text,status varchar(50) COLLATE public.trocaticket_general_ci DEFAULT 'Em planejamento',usuario_id integer REFERENCES usuarios(id));
    CREATE TABLE inscricoes(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,usuario_id integer REFERENCES usuarios(id),evento_id integer REFERENCES eventos(id),data_inscricao timestamptz DEFAULT CURRENT_TIMESTAMP,status text DEFAULT 'Confirmada',UNIQUE(usuario_id,evento_id));
    CREATE TABLE custos_evento(evento_id integer REFERENCES eventos(id) ON DELETE CASCADE,valor integer);INSERT INTO eventos(nome,data,horario,local,categoria,publico,descricao,status,usuario_id)
      VALUES('Histórico','2020-01-01','10:00','Local','Social',50,'Legado','Ativo',7),
      (' Evento legado ','2030-12-10','14:30:45',' Local com espaços ',NULL,50,NULL,'Ativo',7),
      ('Planejamento 1','2030-12-10','10:00','Local','Social',50,'','Em planejamento',7),
      ('Histórico 2','2020-01-02','10:00','Local','Social',50,'','Ativo',7),
      ('Planejamento 2','2030-12-11','10:00','Local','Social',50,'','Em planejamento',7),
      ('Ativo futuro','2030-12-12','10:00','Local','Social',50,'','Ativo',7);
    INSERT INTO inscricoes(usuario_id,evento_id) VALUES(9,1);
    INSERT INTO custos_evento VALUES(1,100);
    CREATE TABLE cotacoes(id integer PRIMARY KEY,evento_id integer REFERENCES eventos(id) ON DELETE CASCADE,criada_em timestamptz DEFAULT CURRENT_TIMESTAMP);INSERT INTO cotacoes(id,evento_id) VALUES(1,1);
    CREATE TABLE itens_cotacao(id integer PRIMARY KEY,cotacao_id integer REFERENCES cotacoes(id) ON DELETE CASCADE);INSERT INTO itens_cotacao VALUES(1,1);
    CREATE TABLE propostas(id integer PRIMARY KEY,cotacao_id integer REFERENCES cotacoes(id),criada_em timestamptz DEFAULT CURRENT_TIMESTAMP);INSERT INTO propostas(id,cotacao_id) VALUES(1,1);
    GRANT SELECT,UPDATE ON usuarios TO service_role;GRANT SELECT ON contas_teste_imagens TO service_role;GRANT SELECT,INSERT,UPDATE ON eventos,inscricoes TO service_role;
    GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
    ALTER TABLE eventos ENABLE ROW LEVEL SECURITY;ALTER TABLE inscricoes ENABLE ROW LEVEL SECURITY;`);

  const pasta=path.join(__dirname,'../../Banco de dados');
  await pool.query(fs.readFileSync(path.join(pasta,'eventos_gestao.incremental.sql'),'utf8'));
  const verificacao=()=>pool.query(fs.readFileSync(path.join(pasta,'eventos_capacidade.verificacao.sql'),'utf8')).then(r=>r.rows[0].verificacao);
  const antes=await verificacao();
  await pool.query(fs.readFileSync(path.join(pasta,'eventos_capacidade.incremental.sql'),'utf8'));
  const depois=await verificacao();
  for(const campo of ['integridade','estados','chaves_estrangeiras','seguranca_tabelas','sequencias'])assert.deepEqual(depois[campo],antes[campo]);
  assert.equal(depois.etapa3.sem_limite,antes.etapa3.sem_limite);
  assert.equal(depois.etapa3.acima_da_capacidade,0);
  await pool.query("INSERT INTO usuarios SELECT n,'participante' FROM generate_series(100,160) n");
  const query=async(sql,args=[])=>{
    const c=await pool.connect();
    try{await c.query('BEGIN');await c.query('SET LOCAL ROLE service_role');const r=await c.query(sql,args);await c.query('COMMIT');return r.rows[0]?.r}
    catch(e){await c.query('ROLLBACK');throw e}finally{c.release()}
  };
  const gerir=(acao,id,versao,d=dados(),usuario=7,chave=null)=>query(
    'SELECT public.gerir_evento_v1($1,$2,$3,$4::jsonb,$5,$6::uuid) AS r',[acao,usuario,id,JSON.stringify(d),versao,chave]);
  const criar=async(capacidade_maxima)=>{
    const e=await gerir('criar',null,null,{...dados(),capacidade_maxima},7,randomUUID());
    return gerir('publicar',e.id,e.versao);
  };
  const inscrever=(u,e)=>query('SELECT public.inscrever_evento_v1($1,$2) AS r',[u,e]);
  const vagas=e=>query('SELECT public.eventos_vagas_v3(ARRAY[$1]::integer[]) AS r',[e]).then(r=>r[0]);
  let e;
  await t.test('vinte concorrentes disputam três vagas sem ultrapassar limite',async()=>{
    e=await criar(3);
    const r=await Promise.allSettled(Array.from({length:20},(_,n)=>inscrever(100+n,e.id)));
    assert.equal(r.filter(r=>r.status==='fulfilled').length,3);
    assert.ok(r.filter(r=>r.status==='rejected').every(r=>r.reason.code==='LT409'));
    assert.deepEqual(await vagas(e.id),{id:e.id,capacidade_maxima:3,inscritos_confirmados:3,vagas_restantes:0,lotado:true});
    const atual=(await pool.query('SELECT versao FROM eventos WHERE id=$1',[e.id])).rows[0];
    assert.equal(atual.versao,e.versao);
  });
  await t.test('redução abaixo de inscritos falha; aumento mantém versão e propriedade',async()=>{
    await assert.rejects(gerir('editar',e.id,e.versao,{...dados(),capacidade_maxima:2}),{code:'CP409'});
    await assert.rejects(gerir('editar',e.id,e.versao,{...dados(),capacidade_maxima:4},8),{code:'EV404'});
    e=await gerir('editar',e.id,e.versao,{...dados(),capacidade_maxima:4});
    await assert.rejects(gerir('editar',e.id,e.versao-1,{...dados(),capacidade_maxima:5}),{code:'EV409'});
    await assert.rejects(query('UPDATE eventos SET capacidade_maxima=1 WHERE id=$1 RETURNING id AS r',[e.id]),{code:'CP409'});
  });
  await t.test('duplicidade concorrente grava somente uma inscrição',async()=>{
    const livre=await criar(10);
    const r=await Promise.allSettled([inscrever(140,livre.id),inscrever(140,livre.id)]);
    assert.equal(r.filter(r=>r.status==='fulfilled').length,1);
    assert.equal(r.find(r=>r.status==='rejected').reason.code,'DU409');
    assert.equal((await vagas(livre.id)).inscritos_confirmados,1);
  });
  await t.test('INSERT direto e reativação também respeitam limite; cancelada libera vaga',async()=>{
    const v=await criar(1);await inscrever(141,v.id);
    await assert.rejects(query('INSERT INTO inscricoes(usuario_id,evento_id) VALUES(142,$1) RETURNING id AS r',[v.id]),{code:'LT409'});
    await query("UPDATE inscricoes SET status='Cancelada' WHERE usuario_id=141 AND evento_id=$1 RETURNING id AS r",[v.id]);
    await inscrever(142,v.id);
    await assert.rejects(query("UPDATE inscricoes SET status='Confirmada' WHERE usuario_id=141 AND evento_id=$1 RETURNING id AS r",[v.id]),{code:'LT409'});
    await assert.rejects(query('UPDATE inscricoes SET evento_id=$1 WHERE usuario_id=142 RETURNING id AS r',[e.id]),{code:'EV409'});
  });
  await t.test('legado sem limite ignora publico; omitir campo preserva limite',async()=>{
    await inscrever(143,2);assert.equal((await vagas(2)).capacidade_maxima,null);
    const v=await criar(1);
    await gerir('editar',v.id,v.versao,dados());
    assert.equal((await vagas(v.id)).capacidade_maxima,1);
  });
  await t.test('edição disputa mesma trava de inscrição; saldo permanece íntegro',async()=>{
    const v=await criar(2);await inscrever(144,v.id);
    await Promise.allSettled([gerir('editar',v.id,v.versao,{...dados(),capacidade_maxima:1}),inscrever(145,v.id)]);
    const s=await vagas(v.id);assert.ok(s.inscritos_confirmados<=s.capacidade_maxima);
  });
  await t.test('cancelamento/horário e nível de isolamento não abrem inscrição',async()=>{
    const v=await criar(2);await gerir('cancelar',v.id,v.versao);
    await assert.rejects(inscrever(146,v.id),{code:'IN409'});
    await assert.rejects(inscrever(146,1),{code:'IN409'});
    const c=await pool.connect();try{
      await c.query('BEGIN ISOLATION LEVEL REPEATABLE READ');
      await assert.rejects(c.query('SELECT public.inscrever_evento_v1(147,$1)',[e.id]),{code:'EV409'});
    }finally{await c.query('ROLLBACK');c.release()}
  });
  await t.test('validação SQL, replay e ACLs',async()=>{
    for(const capacidade_maxima of [0,-1,1.5,'10',2147483648])
      await assert.rejects(gerir('criar',null,null,{...dados(),capacidade_maxima},7,randomUUID()));
    const chave=randomUUID(),d={...dados(),capacidade_maxima:5};
    const a=await gerir('criar',null,null,d,7,chave),b=await gerir('criar',null,null,d,7,chave);assert.equal(a.id,b.id);
    await assert.rejects(gerir('criar',null,null,{...d,capacidade_maxima:6},7,chave),{code:'EV409'});
    const c=await pool.connect();try{
      await c.query('BEGIN');await c.query('SET LOCAL ROLE anon');
      await assert.rejects(c.query('SELECT public.eventos_vagas_v3(ARRAY[1])'),{code:'42501'});
    }finally{await c.query('ROLLBACK');c.release()}
    assert.equal((await verificacao()).etapa3.acima_da_capacidade,0);
  });
});
