'use strict';
// Usa APENAS imagem postgres:17 já instalada. Não baixa imagens, não lê .env,
// não publica portas, não usa rede e não monta diretórios com dados reais.
const test = require('node:test');
const assert = require('node:assert/strict');
const { spawnSync, spawn } = require('node:child_process');
const { randomUUID, createHash } = require('node:crypto');
const { readFileSync } = require('node:fs');
const path = require('node:path');
const imagem = 'postgres:17';
const docker = args => spawnSync('docker', args, { encoding: 'utf8', timeout: 30000, windowsHide: true });
const disponivel = docker(['info', '--format', '{{.ServerVersion}}']);
const motivo = disponivel.status !== 0 ? 'Docker/daemon indisponível: integração PostgreSQL real não executada.' :
  docker(['image', 'inspect', imagem]).status !== 0 ? 'Imagem postgres:17 não instalada; nenhum download autorizado.' : false;
const q = s => "'" + s.replaceAll("'", "''") + "'";

test('PostgreSQL 17 isolado: migração, permissões, rollback e concorrência reais', { skip: motivo, timeout: 90000 }, async () => {
  const nome = 'trocaticket-termos-' + randomUUID();
  let criado = false;
  const argsPsql = ['exec', '-i', nome, 'psql', '-U', 'postgres', '-v', 'ON_ERROR_STOP=1', '-v', 'VERBOSITY=verbose', '-A', '-t'];
  function sql(texto, sucesso = true, codigo = null) {
    const r = spawnSync('docker', argsPsql, { input: texto, encoding: 'utf8', timeout: 15000, windowsHide: true });
    if (sucesso) assert.equal(r.status, 0, r.stderr);
    else {
      assert.equal(r.status, 3, 'Esperada recusa SQL, não falha de infraestrutura: ' + r.stderr);
      if (codigo) assert.match(r.stderr, new RegExp('ERROR:\\s+' + codigo + ':'), r.stderr);
    }
    return r.stdout.trim();
  }
  const qtd = () => sql('SELECT (SELECT count(*) FROM public.usuarios)||\',\'||(SELECT count(*) FROM public.termos_aceites);');
  const senha = '$2b$12$' + 'A'.repeat(53); // Formato sintético, não autentica ninguém.
  const doc = { id: 'termos-uso', versao: 'teste-isolado', estado: 'aprovado', aprovacao: 'exclusivamente-sintetica', secoes: [] };
  const conteudo = JSON.stringify(doc), hash = createHash('sha256').update(conteudo).digest('hex');
  const chamada = (email, versao = doc.versao, h = hash) => `SELECT public.cadastrar_usuario_termos_v1('Pessoa sintética',${q(email)},${q(senha)},'termos-uso',${q(versao)},${q(h)});`;
  function simultanea(texto) {
    return new Promise((resolve, reject) => {
      const p = spawn('docker', argsPsql, { windowsHide: true });
      let stderr = '';
      p.stdout.resume(); p.stderr.on('data', b => { stderr += b; });
      p.on('error', reject); p.on('close', code => resolve({ code, stderr })); p.stdin.end(texto);
    });
  }
  try {
    const inicio = docker(['run', '-d', '--network', 'none', '--name', nome, '--label', 'trocaticket.tests=termos',
      '--tmpfs', '/var/lib/postgresql/data:rw,noexec,nosuid', '-e', 'POSTGRES_HOST_AUTH_METHOD=trust', imagem]);
    assert.equal(inicio.status, 0, inicio.stderr); criado = true;
    const inspecao = docker(['inspect', nome]);
    assert.equal(inspecao.status, 0);
    const ambiente = JSON.parse(inspecao.stdout)[0];
    assert.equal(ambiente.HostConfig.NetworkMode, 'none');
    assert.equal(Object.keys(ambiente.HostConfig.PortBindings || {}).length, 0);
    assert.ok(ambiente.Mounts.every(m => m.Type === 'tmpfs'));
    // Docker registra --tmpfs em HostConfig.Tmpfs, podendo omiti-lo em Mounts.
    assert.ok(Object.hasOwn(ambiente.HostConfig.Tmpfs || {}, '/var/lib/postgresql/data'));
    const sistemaArquivos = docker(['exec', nome, 'stat', '-f', '-c', '%T', '/var/lib/postgresql/data']);
    assert.equal(sistemaArquivos.status, 0); assert.equal(sistemaArquivos.stdout.trim(), 'tmpfs');
    let pronto = false;
    for (let i = 0; i < 40; i++) {
      if (docker(['exec', nome, 'pg_isready', '-U', 'postgres']).status === 0) { pronto = true; break; }
      await new Promise(r => setTimeout(r, 250));
    }
    assert.ok(pronto, 'PostgreSQL descartável não iniciou');
    assert.match(sql('SHOW server_version;'), /^17\./);
    sql(`CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN; CREATE ROLE service_role NOLOGIN BYPASSRLS;
      CREATE TYPE public.usuarios_perfil_enum AS ENUM('participante','organizador','fornecedor','admin');
      CREATE TABLE public.usuarios(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nome varchar(100) NOT NULL,
        email varchar(150) NOT NULL UNIQUE,senha varchar(100) NOT NULL,perfil public.usuarios_perfil_enum NOT NULL);
      GRANT USAGE ON SCHEMA public TO service_role;
      GRANT SELECT,INSERT ON public.usuarios TO service_role;
      GRANT USAGE ON SEQUENCE public.usuarios_id_seq TO service_role;
      INSERT INTO public.usuarios(nome,email,senha,perfil) VALUES('Legado sintético','legado@example.invalid',${q(senha)},'participante');`);
    const legado = sql("SELECT md5(to_jsonb(u)::text) FROM public.usuarios u WHERE id=1;");
    const preflight = readFileSync(path.join(__dirname, '../../Banco de dados/termos_aceite.preflight.sql'), 'utf8');
    sql(preflight);
    const migration = readFileSync(path.join(__dirname, '../../Banco de dados/termos_aceite.incremental.sql'), 'utf8');
    // Falha tardia de precondição deve desfazer inclusive tabelas e funções novas.
    sql('REVOKE USAGE ON SEQUENCE public.usuarios_id_seq FROM service_role;');
    sql(migration, false, 'P0001');
    assert.equal(sql("SELECT to_regclass('public.termos_documentos') IS NULL AND to_regclass('public.termos_aceites') IS NULL AND to_regprocedure('public.cadastrar_usuario_termos_v1(text,text,text,text,text,text)') IS NULL AND to_regprocedure('public.termos_publicacao_bloquear_v1(text,text,text)') IS NULL;"), 't');
    assert.equal(sql('SELECT count(*) FROM public.usuarios;'), '1');
    sql('GRANT USAGE ON SEQUENCE public.usuarios_id_seq TO service_role;');
    sql(migration); assert.equal(qtd(), '1,0');
    const verificacao = readFileSync(path.join(__dirname, '../../Banco de dados/termos_aceite.verificacao.sql'), 'utf8');
    sql(verificacao);
    sql(migration, false, 'P0001'); // Reaplicação aborta sem substituir objetos ou dados.
    assert.equal(qtd(), '1,0');
    assert.equal(sql("SELECT count(*) FROM pg_class WHERE oid IN('public.termos_documentos'::regclass,'public.termos_aceites'::regclass) AND relrowsecurity AND relforcerowsecurity;"), '2');
    assert.equal(sql('SELECT count(*) FROM public.termos_documentos WHERE ativo;'), '0');
    sql('SET ROLE service_role;' + chamada('minuta@example.invalid', 'A.1'), false, 'PT409'); assert.equal(qtd(), '1,0');
    sql(`INSERT INTO public.termos_documentos(documento_id,versao,hash,conteudo,ativo,aprovado_em,aprovacao_referencia)
      VALUES('termos-uso',${q(doc.versao)},${q(hash)},${q(conteudo)},true,clock_timestamp(),'teste-sintetico');`);
    for (const papel of ['anon', 'authenticated']) {
      sql(`SET ROLE ${papel};` + chamada('recusado@example.invalid'), false, '42501');
      sql(`SET ROLE ${papel};SELECT * FROM public.termos_aceites;`, false, '42501');
      sql(`SET ROLE ${papel};SELECT public.termos_publicacao_bloquear_v1('termos-uso',${q(doc.versao)},${q(hash)});`, false, '42501');
    }
    sql('SET ROLE service_role;UPDATE public.termos_documentos SET ativo=false;', false, '42501');
    sql('SET ROLE service_role;DELETE FROM public.termos_aceites;', false, '42501');
    sql('SET ROLE service_role;' + chamada('antigo@example.invalid', 'antiga'), false, 'PT409');
    sql('SET ROLE service_role;' + chamada('hash@example.invalid', doc.versao, 'b'.repeat(64)), false, 'PT409');
    // A assinatura não permite indicar usuário nem instante do aceite.
    sql('SET ROLE service_role;' + chamada('injetado@example.invalid').replace(');', ',p_usuario_id=>1);'), false, '42883');
    sql('SET ROLE service_role;' + chamada('data@example.invalid').replace(');', ",p_aceito_em=>'2000-01-01');"), false, '42883');
    assert.equal(qtd(), '1,0');
    sql('SET ROLE service_role;' + chamada('cadastro@example.invalid'));
    assert.equal(qtd(), '2,1');
    assert.equal(sql("SELECT count(*) FROM public.termos_aceites a JOIN public.usuarios u ON u.id=a.usuario_id WHERE u.email='cadastro@example.invalid' AND a.fluxo='cadastro' AND a.aceito_em BETWEEN now()-interval '1 minute' AND now();"), '1');
    sql('SET ROLE service_role;' + chamada('cadastro@example.invalid'), false, '23505'); assert.equal(qtd(), '2,1');
    sql(`CREATE FUNCTION public.falha_aceite_teste() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RAISE EXCEPTION 'Falha sintética'; END$$;
      CREATE TRIGGER falha_aceite_teste BEFORE INSERT ON public.termos_aceites FOR EACH ROW EXECUTE FUNCTION public.falha_aceite_teste();`);
    sql('SET ROLE service_role;' + chamada('rollback@example.invalid'), false, 'P0001');
    assert.equal(qtd(), '2,1');
    assert.equal(sql("SELECT count(*) FROM public.usuarios WHERE email='rollback@example.invalid';"), '0');
    sql('DROP TRIGGER falha_aceite_teste ON public.termos_aceites; DROP FUNCTION public.falha_aceite_teste();');
    async function aguardarSessao(condicao) {
      for (let i = 0; i < 30; i++) {
        if (sql(`SELECT count(*) FROM pg_stat_activity WHERE ${condicao};`) === '1') return;
        await new Promise(r => setTimeout(r, 50));
      }
      assert.fail('Não foi possível comprovar a sobreposição das transações: ' + condicao);
    }
    const primeira = simultanea("SET application_name='termos-concorrente-a';BEGIN;SET ROLE service_role;" + chamada('concorrente@example.invalid') + 'SELECT pg_sleep(3);COMMIT;');
    await aguardarSessao("application_name='termos-concorrente-a' AND wait_event='PgSleep'");
    const segunda = simultanea("SET application_name='termos-concorrente-b';BEGIN;SET ROLE service_role;" + chamada('concorrente@example.invalid') + 'COMMIT;');
    await aguardarSessao("application_name='termos-concorrente-b' AND wait_event_type='Lock'");
    const disputas = await Promise.all([primeira, segunda]);
    assert.equal(disputas.filter(r => r.code === 0).length, 1);
    const recusadas = disputas.filter(r => r.code !== 0);
    assert.equal(recusadas.length, 1); assert.equal(recusadas[0].code, 3);
    assert.match(recusadas[0].stderr, /ERROR:\s+23505:/); assert.equal(qtd(), '3,2');
    assert.equal(sql('SELECT count(*) FROM public.termos_aceites WHERE usuario_id=1;'), '0');
    assert.equal(sql('SELECT md5(to_jsonb(u)::text) FROM public.usuarios u WHERE id=1;'), legado);
  } finally {
    if (criado) {
      const dono = docker(['inspect', '--format', '{{index .Config.Labels "trocaticket.tests"}}', nome]);
      assert.equal(dono.status, 0); assert.equal(dono.stdout.trim(), 'termos');
      const fim = docker(['rm', '-f', nome]); // Exclusivamente o contêiner sintético desta execução.
      assert.equal(fim.status, 0, 'Remoção do contêiner descartável não confirmada');
    }
  }
});
