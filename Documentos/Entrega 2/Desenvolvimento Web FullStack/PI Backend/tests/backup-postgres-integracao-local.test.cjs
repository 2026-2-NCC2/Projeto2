function privado(dir) {
  if (process.platform !== 'win32') { fs.chmodSync(dir, 0o700); return; }
  const r = spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command',
    '$ErrorActionPreference="Stop"; $p=$env:TT_BACKUP_DIR; $sid=[Security.Principal.WindowsIdentity]::GetCurrent().User; $a=New-Object Security.AccessControl.DirectorySecurity; $a.SetOwner($sid); $a.SetAccessRuleProtection($true,$false); foreach($s in @($sid.Value,"S-1-5-18","S-1-5-32-544")){ $i=New-Object Security.Principal.SecurityIdentifier($s); $r=New-Object Security.AccessControl.FileSystemAccessRule($i,"FullControl","ContainerInherit,ObjectInherit","None","Allow"); $a.AddAccessRule($r) }; Set-Acl -LiteralPath $p -AclObject $a'],
  { windowsHide: true, stdio: 'pipe', timeout: 10000, env: { ...process.env, TT_BACKUP_DIR: dir } });
  assert.equal(r.status, 0, 'ACL_TEMPORARIA_PRIVADA');
}
test('V2: dois ciclos reais locais, origem removida, negativos e limpeza', {
  skip: process.env.TROCATICKET_BACKUP_V2_LOCAL !== '1', timeout: 300000,
}, async t => {
  const docker = await v2.dockerLocal();
  const image = (await docker(['image', 'inspect', 'postgres:17', '--format', '{{.Id}}'])).trim();
  await docker(['image', 'inspect', 'supabase/postgres:17.11.0.016']);
  const roots = [], sources = new Set();
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tt-v2-integracao-')); privado(root);
  const destination = () => { const p = fs.mkdtempSync(path.join(root, 'pacote-')); privado(p); roots.push(p); return p; };
  const copiar = dir => { const dest = destination(); for (const n of ['manifest-v2.json', 'database.dump', 'roles.sql']) fs.copyFileSync(path.join(dir, n), path.join(dest, n)); return dest; };
  async function manifesto(dir, alterar) { const f = path.join(dir, 'manifest-v2.json'); const m = JSON.parse(fs.readFileSync(f)); await alterar(m); fs.writeFileSync(f, JSON.stringify(m), { mode: 0o600 }); }
  async function removerOrigem(name) {
    const [c] = JSON.parse(await docker(['inspect', name]));
    assert.equal(c.Name, '/' + name); assert.equal(c.Config.Labels['tt.backup.source'], name);
    await docker(['stop', '--time', '1', name]); await docker(['rm', '--volumes', name]); sources.delete(name);
  }
  try {
    for (let ciclo = 1; ciclo <= 2; ciclo++) await t.test('ciclo completo ' + ciclo, async ct => {
      const name = 'tt-backup-source-' + randomUUID();

      sources.add(name);
      await docker(['run', '--detach', '--pull=never', '--name', name, '--label', 'tt.backup.source=' + name,
        '--network', 'none', '--read-only', '--user', 'postgres',
        '--tmpfs', '/tmp:rw,size=128m,mode=1777', '--tmpfs', '/var/lib/postgresql/data:rw,size=16m,uid=999,gid=999',
        '--tmpfs', '/isolated:rw,size=256m,uid=999,gid=999,mode=0700', '--entrypoint', '/bin/sh', image, '-c',
        'initdb -D /isolated/data -U supabase_admin --auth-local=trust --auth-host=reject --no-locale --encoding=UTF8 >/tmp/init.log 2>&1 && exec postgres -D /isolated/data -k /tmp -c listen_addresses=']);
      const sql = async q => docker(['exec', '-i', name, 'psql', '-X', '-qAt', '-h', '/tmp', '-U', 'supabase_admin', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1'], { input: Readable.from([q]) });
      const deadline = Date.now() + 30000; let ready = false;
      while (Date.now() < deadline) { try { ready = (await sql('SELECT 1;')).trim() === '1'; if (ready) break; } catch {} await new Promise(r => setTimeout(r, 100)); }
      assert.ok(ready); await sql(fixtureSql);
      const dir = destination();
      const beforeLoad = require('node:module')._load;
      const fsRead = fs.readFileSync;
      try {
        // Qualquer tentativa de ler .env ou carregar dotenv reprova o teste local.
        fs.readFileSync = function (f, ...args) { if (typeof f === 'string' && /(^|[\\/])\.env$/.test(f)) throw Error('ENV_ORIGEM_RECUSADO'); return fsRead.call(this, f, ...args); };
        require('node:module')._load = function (name, ...args) { if (name === 'dotenv') throw Error('DOTENV_RECUSADO'); return beforeLoad.call(this, name, ...args); };
        const r = await v2.backup(dir, { autorizado: true, escritasPausadas: true, origemLocal: name });
        assert.equal(r.status, 'BACKUP_COMPLETO_GERADO');
      } finally { fs.readFileSync = fsRead; require('node:module')._load = beforeLoad; }
      const m = JSON.parse(fs.readFileSync(path.join(dir, 'manifest-v2.json')));
      assert.equal(fs.readFileSync(path.join(dir, 'database.dump')).subarray(0, 5).toString(), 'PGDMP');
      assert.equal(m.reference.tables.find(x => x.name === 'vazia').count, '0');
      assert.equal(m.reference.tables.find(x => x.name === 'duplicados').count, '3');
      assert.equal(m.reference.catalogo.sequences.find(x => x.name === 'contador').last, '9007199254740995');
      await removerOrigem(name);
      assert.equal((await docker(['ps', '-a', '--filter', 'name=^/' + name + '$', '--format', '{{.Names}}'])).trim(), '');
      const r = await v2.restaurar(dir, { autorizado: true, docker });
      assert.equal(r.status, 'RESTAURACAO_OFFLINE_APROVADA');
      t.diagnostic('Ciclo ' + ciclo + ': pg_dump/pg_restore reais, origem ausente, catálogo e dados idênticos.');
      if (ciclo === 1) {
        for (const scenario of ['ausente', 'adulterado', 'manifesto', 'estrutura', 'dados', 'dependencia', 'restore']) await ct.test('negativo ' + scenario, async () => {
          const dest = copiar(dir);
          if (scenario === 'ausente') fs.unlinkSync(path.join(dest, 'roles.sql'));
          if (scenario === 'adulterado') { const f = path.join(dest, 'database.dump'); const b = fs.readFileSync(f); b[b.length - 1] ^= 1; fs.writeFileSync(f, b); }
          if (scenario === 'manifesto') await manifesto(dest, m => { m.version = 999; });
          if (scenario === 'estrutura') await manifesto(dest, m => { m.reference.catalogo.relations[0].owner = 'owner_invalido'; });
          if (scenario === 'dados') await manifesto(dest, m => { m.reference.tables.find(t => t.name === 'duplicados').count = '4'; });
          if (scenario === 'restore') {
            const f = path.join(dest, 'database.dump'); fs.writeFileSync(f, 'PGDMP-arquivo-quebrado');
            await manifesto(dest, async m => { const a = m.artifacts.find(x => x.name === 'database.dump'); a.bytes = fs.statSync(f).size; a.sha256 = await v2.hashFile(f); });
          }
          let restoreCalled = false;
          const run = async (args, opts) => {
            if (args[0] === 'exec' && args.includes('pg_restore')) {
              restoreCalled = true;
              if (scenario === 'dependencia') await docker(['exec', '-i', args[1], 'psql', '-X', '-qAt', '-h', '/tmp', '-U', 'supabase_admin', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1'], { input: Readable.from(['DROP ROLE fixture_reader;']) });
            }
            return docker(args, opts);
          };
          await assert.rejects(v2.restaurar(dest, { autorizado: true, docker: run }), e => {
            if (['estrutura', 'dados'].includes(scenario)) return e.code === 'MANIFESTO_DIVERGENTE';
            if (['dependencia', 'restore'].includes(scenario)) return e.code === 'SUBPROCESSO';
            return Boolean(e);
          });
          if (['ausente', 'adulterado', 'manifesto'].includes(scenario)) assert.equal(restoreCalled, false);
          if (['dependencia', 'restore'].includes(scenario)) assert.equal(restoreCalled, true);
        });
      }
    });
  } catch (e) { t.diagnostic(JSON.stringify({ code: e.code, campos: e.campos, name: e.name })); throw e; }
  finally {
    for (const name of sources) await removerOrigem(name);
    for (const dir of roots) {
      assert.equal(path.dirname(fs.realpathSync(dir)), fs.realpathSync(root));
      for (const name of fs.readdirSync(dir)) { const f = path.join(dir, name); assert.ok(fs.lstatSync(f).isFile()); fs.unlinkSync(f); }
      fs.rmdirSync(dir);
    }
    assert.equal(path.dirname(fs.realpathSync(root)), fs.realpathSync(os.tmpdir())); fs.rmdirSync(root);
  }
});
